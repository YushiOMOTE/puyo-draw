import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { generatePattern, PATTERN_COUNT } from "../tokopuyo/queue.js";
import {
  TSUMO_SEARCH_ALPHABET,
  patternSequence,
} from "../tokopuyo/tsumo-search.js";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT_PATH = path.join(ROOT, "tokopuyo", "tsumo-search-index.js");
const MAX_INDEXED_LENGTH = 6;
const MAX_DISPLAY_CANDIDATES = 5;

function createNode(parent = -1, symbol = -1, depth = 0) {
  return { parent, symbol, depth, children: new Map(), seeds: [] };
}

function buildIndex() {
  const nodes = [createNode()];

  for (let seed = 0; seed < PATTERN_COUNT; seed += 1) {
    const sequence = patternSequence(generatePattern(seed));
    if (sequence.length !== 256) {
      throw new Error(`Seed ${seed} generated ${sequence.length} puyos`);
    }

    let nodeIndex = 0;
    nodes[nodeIndex].seeds.push(seed);
    for (let depth = 0; depth < MAX_INDEXED_LENGTH; depth += 1) {
      const symbol = sequence[depth];
      let childIndex = nodes[nodeIndex].children.get(symbol);
      if (childIndex === undefined) {
        childIndex = nodes.length;
        nodes[nodeIndex].children.set(symbol, childIndex);
        nodes.push(createNode(nodeIndex, symbol, depth + 1));
      }
      nodeIndex = childIndex;
      nodes[nodeIndex].seeds.push(seed);
    }
  }

  const nodeFirstChild = [];
  const nodeChildCount = [];
  const nodeCandidateStart = [];
  const nodeCandidateCount = [];
  const childSymbol = [];
  const childNode = [];
  const candidateSeeds = [];

  const orderedNodes = [];
  const pending = [0];
  while (pending.length) {
    const nodeIndex = pending.shift();
    const node = nodes[nodeIndex];
    orderedNodes.push(nodeIndex);
    const children = [...node.children.entries()].sort(([left], [right]) =>
      TSUMO_SEARCH_ALPHABET.indexOf(left) - TSUMO_SEARCH_ALPHABET.indexOf(right));
    pending.push(...children.map(([, index]) => index));
  }
  const orderedIndex = new Map(orderedNodes.map((nodeIndex, index) => [nodeIndex, index]));

  for (const nodeIndex of orderedNodes) {
    const node = nodes[nodeIndex];
    const children = [...node.children.entries()].sort(([left], [right]) =>
      TSUMO_SEARCH_ALPHABET.indexOf(left) - TSUMO_SEARCH_ALPHABET.indexOf(right));
    nodeFirstChild.push(childNode.length);
    nodeChildCount.push(children.length);
    for (const [symbol, childIndex] of children) {
      childSymbol.push(TSUMO_SEARCH_ALPHABET.indexOf(symbol));
      childNode.push(orderedIndex.get(childIndex));
    }

    const sortedSeeds = [...node.seeds].sort((left, right) => left - right);
    const retainedSeeds = node.depth < MAX_INDEXED_LENGTH
      ? sortedSeeds.slice(0, MAX_DISPLAY_CANDIDATES)
      : sortedSeeds;
    if (node.depth === MAX_INDEXED_LENGTH && retainedSeeds.length > 255) {
      throw new Error(`6-symbol prefix has ${retainedSeeds.length} candidates; Uint8Array cannot represent the count`);
    }
    nodeCandidateStart.push(candidateSeeds.length);
    nodeCandidateCount.push(retainedSeeds.length);
    candidateSeeds.push(...retainedSeeds);
  }

  return {
    version: 1,
    patternCount: PATTERN_COUNT,
    maxIndexedLength: MAX_INDEXED_LENGTH,
    alphabet: TSUMO_SEARCH_ALPHABET,
    nodeFirstChild,
    nodeChildCount,
    nodeCandidateStart,
    nodeCandidateCount,
    childSymbol,
    childNode,
    candidateSeeds,
  };
}

function encodeArray(values, type) {
  const typed = new globalThis[type](values);
  return Buffer.from(typed.buffer, typed.byteOffset, typed.byteLength).toString("base64");
}

function formatEncodedArray(name, values, type) {
  return `${name}: decodeBase64(${JSON.stringify(encodeArray(values, type))}, ${type})`;
}

function serialize(index) {
  return `// Generated by scripts/generate-tokopuyo-tsumo-index.mjs. Do not edit.\n` +
    `function decodeBase64(value, Type) {\n` +
    `  const binary = atob(value);\n` +
    `  const bytes = Uint8Array.from(binary, (character) => character.charCodeAt(0));\n` +
    `  return new Type(bytes.buffer);\n` +
    `}\n\n` +
    `export const TSUMO_SEARCH_INDEX = {\n` +
    `  version: ${index.version},\n` +
    `  patternCount: ${index.patternCount},\n` +
    `  maxIndexedLength: ${index.maxIndexedLength},\n` +
    `  alphabet: ${JSON.stringify(index.alphabet)},\n` +
    `${formatEncodedArray("nodeFirstChild", index.nodeFirstChild, "Uint32Array")},\n` +
    `${formatEncodedArray("nodeChildCount", index.nodeChildCount, "Uint8Array")},\n` +
    `${formatEncodedArray("nodeCandidateStart", index.nodeCandidateStart, "Uint32Array")},\n` +
    `${formatEncodedArray("nodeCandidateCount", index.nodeCandidateCount, "Uint8Array")},\n` +
    `${formatEncodedArray("childSymbol", index.childSymbol, "Uint8Array")},\n` +
    `${formatEncodedArray("childNode", index.childNode, "Uint32Array")},\n` +
    `${formatEncodedArray("candidateSeeds", index.candidateSeeds, "Uint16Array")},\n` +
    `};\n`;
}

function assertEqual(actual, expected, label) {
  if (actual.length !== expected.length) {
    throw new Error(`${label} length mismatch: ${actual.length} !== ${expected.length}`);
  }
  for (let index = 0; index < actual.length; index += 1) {
    if (actual[index] !== expected[index]) {
      throw new Error(`${label}[${index}] mismatch: ${actual[index]} !== ${expected[index]}`);
    }
  }
}

async function verifyGenerated(index) {
  const module = await import(`${pathToFileURL(OUTPUT_PATH).href}?verify=${Date.now()}`);
  const actual = module.TSUMO_SEARCH_INDEX;
  for (const key of [
    "nodeFirstChild",
    "nodeChildCount",
    "nodeCandidateStart",
    "nodeCandidateCount",
    "childSymbol",
    "childNode",
    "candidateSeeds",
  ]) {
    assertEqual(actual[key], index[key], key);
  }
  for (const key of ["version", "patternCount", "maxIndexedLength", "alphabet"]) {
    if (actual[key] !== index[key]) {
      throw new Error(`${key} mismatch: ${actual[key]} !== ${index[key]}`);
    }
  }

  for (let seed = 0; seed < PATTERN_COUNT; seed += 1) {
    const sequence = patternSequence(generatePattern(seed));
    if (sequence.length !== 256) throw new Error(`Invalid sequence at seed ${seed}`);
  }
}

const index = buildIndex();
if (process.argv.includes("--check")) {
  await verifyGenerated(index);
  console.log(`Verified ${index.patternCount} patterns in ${OUTPUT_PATH}`);
} else {
  await fs.writeFile(OUTPUT_PATH, serialize(index), "utf8");
  console.log(`Generated ${index.patternCount} patterns, ${index.nodeFirstChild.length} Trie nodes`);
  console.log(`Wrote ${OUTPUT_PATH}`);
}
